// Generates the server secrets.
//
//   pnpm --filter @toolbox/server keys          → development
//     writes server/.dev.vars (secrets for `wrangler dev`) and
//     src-tauri/keys/entitlement_public.b64 (public key the desktop app
//     embeds in debug builds). Existing files are kept unless --force.
//
//   pnpm --filter @toolbox/server keys --prod   → production
//     prints the three secrets for `wrangler secret put` and the public key
//     to set as TOOLBOX_ENTITLEMENT_PUBLIC_KEY when building the release app.
//     Nothing is written to disk.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { webcrypto } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const prod = process.argv.includes("--prod");
const force = process.argv.includes("--force");

const b64 = (bytes) => Buffer.from(bytes).toString("base64");
const random = (n) => b64(webcrypto.getRandomValues(new Uint8Array(n)));

const pair = await webcrypto.subtle.generateKey({ name: "Ed25519" }, true, ["sign", "verify"]);
const privateKey = b64(new Uint8Array(await webcrypto.subtle.exportKey("pkcs8", pair.privateKey)));
const publicKey = b64(new Uint8Array(await webcrypto.subtle.exportKey("raw", pair.publicKey)));
const secrets = {
  JWT_SECRET: random(48),
  DOWNLOAD_SIGNING_KEY: random(48),
  ENTITLEMENT_PRIVATE_KEY: privateKey,
};

if (prod) {
  console.log("Produção — rode cada comando e cole o valor quando pedido:\n");
  for (const [name, value] of Object.entries(secrets)) {
    console.log(`npx wrangler secret put ${name}\n  ${value}\n`);
  }
  console.log("Chave pública (defina ao compilar o app de produção):");
  console.log(`  TOOLBOX_ENTITLEMENT_PUBLIC_KEY=${publicKey}\n`);
  console.log("Guarde a chave privada num cofre: trocá-la exige publicar uma nova versão do app.");
  process.exit(0);
}

const devVars = resolve(here, "../.dev.vars");
const publicKeyFile = resolve(here, "../../src-tauri/keys/entitlement_public.b64");
if ((existsSync(devVars) || existsSync(publicKeyFile)) && !force) {
  console.log("Chaves de desenvolvimento já existem (use --force para gerar novas).");
  process.exit(0);
}
writeFileSync(
  devVars,
  [
    "# Development secrets — generated by scripts/generate-keys.mjs. Never commit.",
    ...Object.entries(secrets).map(([k, v]) => `${k}="${v}"`),
    '# E-mails that become admin on signup/login (comma-separated).',
    'ADMIN_EMAILS=""',
    "",
  ].join("\n"),
);
mkdirSync(dirname(publicKeyFile), { recursive: true });
writeFileSync(publicKeyFile, publicKey + "\n");
console.log(`Escrito: ${devVars}`);
console.log(`Escrito: ${publicKeyFile}`);
